import fs from 'node:fs'
import path from 'node:path'

/**
 * Make a drag-and-drop deploy of `dist/` behave like a repo deploy.
 *
 * Netlify reads `netlify.toml` and uploads `netlify/functions/*` when a site is
 * built from the repository — but a manually dropped folder *becomes* the deploy
 * root, and the only function Netlify will pick up from it is one that sits at
 * `netlify/functions/` inside that folder. Without this step the site ships with
 * no `/api/lyrics`, and online lyrics silently resolve to nothing.
 *
 * So the build copies the function in and writes the rewrite beside it. Nothing
 * secret is copied: the function only reads its provider URLs from environment
 * variables.
 */
const dist = 'dist'
const src = path.join('netlify', 'functions')
const dest = path.join(dist, 'netlify', 'functions')

if (!fs.existsSync(dist)) {
  console.error('prepare-netlify-dist: dist/ not found — run `vite build` first')
  process.exit(1)
}

let copied = 0
if (fs.existsSync(src)) {
  fs.mkdirSync(dest, { recursive: true })
  for (const file of fs.readdirSync(src)) {
    if (!file.endsWith('.mjs') && !file.endsWith('.js')) continue
    fs.copyFileSync(path.join(src, file), path.join(dest, file))
    copied += 1
  }
}

// The app asks for `/api/lyrics`; point that at the function, and let the SPA
// fallback catch everything else (hash routing means real paths are rare).
const redirects = [
  '# Generated by scripts/prepare-netlify-dist.mjs — do not edit in dist/',
  '/api/lyrics  /.netlify/functions/lyrics  200',
  '/*  /index.html  200',
].join('\n') + '\n'
fs.writeFileSync(path.join(dist, '_redirects'), redirects, 'utf8')

console.log(`prepare-netlify-dist: ${copied} function file(s) + _redirects written to ${dist}/`)
